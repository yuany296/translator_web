// 去重后拼成一个字符类，命中任意一个即为繁体专用字
const TRADITIONAL_ONLY_RE = new RegExp(`[${[...new Set(TRADITIONAL_ONLY_CHARS.join(""))].join("")}]`, "u");

/** 译文里出现的繁体专用字（去重，便于在提示里举反例）。 */
export function findTraditionalChars(text) {
  const found = new Set();
  for (const character of String(text || "")) {
    if (TRADITIONAL_ONLY_RE.test(character)) found.add(character);
  }
  return [...found];
}

/** 定点修正时用的指令；没有繁体字就返回空串（调用方据此判断这一段要不要修）。 */
export function describeScriptFix(text) {
  const examples = findTraditionalChars(text).slice(0, 4);
  if (!examples.length) return "";
  return `本段必须全部改用简体中文，不要出现任何繁体字（例如「${examples.join("」「")}」）；只改字形，其它内容一字不动`;
}
