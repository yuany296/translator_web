/**
 * 「繁体专用字」的**唯一定义**：这些字在规范的简体文本里不会出现（简体有对应的另一个字），
 * 因此命中任意一个就能断定这段文字是繁体。
 *
 * 两处消费者问的其实是同一个问题「这段是不是繁体」，以前各写一份字符集，
 * 于是「源语言判定」与「手机版字形漂移兜底」会给出不同答案：
 *   - `shared/languages.js#resolveSourceLanguage`（zh-CN / zh-TW 判定）
 *   - 手机版字形兜底（`script-guard.js`：把模型写成繁体的一段捞出来重问）
 *
 * 含糊的字（著、於、乾、唸、里、只……）一律不收：命中就意味着"要动手改"，
 * 宁可漏判也不误判 —— 误判会白白多花一次模型请求，或把简体文本当成繁体路由。
 */

